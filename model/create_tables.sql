-- =====================================================================
-- create_tables.sql  |  Assignment 2.1  |  Retail Sales Snowflake Schema
-- =====================================================================
-- Order: drops first (children before parents), then creates (parents before
-- children), so the script runs in one pass and can be re-run.
-- Flags: CURR_FLG TRUE = current row.
-- =====================================================================

DROP TABLE IF EXISTS AGG_SLS_CATEGORY_CITY_MONTH;
DROP TABLE IF EXISTS FCT_INVENTORY;
DROP TABLE IF EXISTS FCT_PRICE;
DROP TABLE IF EXISTS FCT_SALES;
DROP TABLE IF EXISTS DIM_DAY;
DROP TABLE IF EXISTS DIM_MONTH;
DROP TABLE IF EXISTS DIM_YEAR;
DROP TABLE IF EXISTS DIM_CUSTOMER;
DROP TABLE IF EXISTS DIM_LOCN;
DROP TABLE IF EXISTS DIM_CITY;
DROP TABLE IF EXISTS DIM_REGION;
DROP TABLE IF EXISTS DIM_ITEM;
DROP TABLE IF EXISTS DIM_SUBCATEGORY;
