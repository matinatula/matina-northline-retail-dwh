    EFF_FROM_DT     DATE          NOT NULL,
    EFF_TO_DT       DATE          NOT NULL DEFAULT DATE '9999-12-31',
    REC_INS_TS      TIMESTAMP     NOT NULL,
    REC_UPDT_TS     TIMESTAMP     NOT NULL,
    SRC_SYS_CD      VARCHAR(30)   NOT NULL,
    BATCH_ID        VARCHAR(50)   NOT NULL,
    CONSTRAINT PK_DIM_ITEM PRIMARY KEY (ITEM_KY),
    CONSTRAINT UQ_DIM_ITEM_VERSION UNIQUE (ITEM_ID, EFF_FROM_DT),
    CONSTRAINT FK_ITEM_SUBCATEGORY FOREIGN KEY (SUBCATEGORY_KY)
        REFERENCES DIM_SUBCATEGORY (SUBCATEGORY_KY),
    CONSTRAINT FK_ITEM_BRAND FOREIGN KEY (BRAND_KY)
        REFERENCES DIM_BRAND (BRAND_KY)
);


