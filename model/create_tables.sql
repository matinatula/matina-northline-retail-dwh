-- ---------------------------------------------------------------------
-- FACTS
-- Transaction fact: no CURR_FLG, no EFF_*_DT
-- ---------------------------------------------------------------------
CREATE TABLE FCT_SALES (
    SALES_KY        INT            NOT NULL,
    TRANSACTION_ID  VARCHAR(50)    NOT NULL,
    LINE_NUMBER     INT            NOT NULL,
    ITEM_KY         INT            NOT NULL,
    LOCN_KY         INT            NOT NULL,
    DAY_KY          INT            NOT NULL,
    CUSTOMER_KY     INT,
    SLS_QTY         DECIMAL(18,3)  NOT NULL,
    SLS_AMT         DECIMAL(18,2)  NOT NULL,
    DSC_AMT         DECIMAL(18,2),
    REC_INS_TS      TIMESTAMP      NOT NULL,
    REC_UPDT_TS     TIMESTAMP      NOT NULL,
    SRC_SYS_CD      VARCHAR(30)    NOT NULL,
    BATCH_ID        VARCHAR(50)    NOT NULL,
    CONSTRAINT PK_FCT_SALES PRIMARY KEY (SALES_KY),
    CONSTRAINT UQ_FCT_SALES_GRAIN UNIQUE
        (TRANSACTION_ID, LINE_NUMBER, ITEM_KY, LOCN_KY, DAY_KY),
    CONSTRAINT FK_SALES_ITEM     FOREIGN KEY (ITEM_KY)
        REFERENCES DIM_ITEM (ITEM_KY),
    CONSTRAINT FK_SALES_LOCN     FOREIGN KEY (LOCN_KY)
        REFERENCES DIM_LOCN (LOCN_KY),
    CONSTRAINT FK_SALES_DAY      FOREIGN KEY (DAY_KY)
        REFERENCES DIM_DAY (DAY_KY),
    CONSTRAINT FK_SALES_CUSTOMER FOREIGN KEY (CUSTOMER_KY)
        REFERENCES DIM_CUSTOMER (CUSTOMER_KY)
);

-- Positional fact: carries EFF_FROM_DT / EFF_TO_DT, no CURR_FLG
CREATE TABLE FCT_PRICE (
    PRICE_KY        INT            NOT NULL,
    ITEM_KY         INT            NOT NULL,
    LOCN_KY         INT            NOT NULL,
    DAY_KY          INT            NOT NULL,
    PRICE_AMT       DECIMAL(18,2)  NOT NULL,
    EFF_FROM_DT     DATE           NOT NULL,
    EFF_TO_DT       DATE          NOT NULL DEFAULT DATE '9999-12-31',
    REC_INS_TS      TIMESTAMP      NOT NULL,
    REC_UPDT_TS     TIMESTAMP      NOT NULL,
    SRC_SYS_CD      VARCHAR(30)    NOT NULL,
    BATCH_ID        VARCHAR(50)    NOT NULL,
    CONSTRAINT PK_FCT_PRICE PRIMARY KEY (PRICE_KY),
    CONSTRAINT UQ_FCT_PRICE_GRAIN UNIQUE (ITEM_KY, LOCN_KY, DAY_KY),
    CONSTRAINT FK_PRICE_ITEM FOREIGN KEY (ITEM_KY)
        REFERENCES DIM_ITEM (ITEM_KY),
    CONSTRAINT FK_PRICE_LOCN FOREIGN KEY (LOCN_KY)
        REFERENCES DIM_LOCN (LOCN_KY),
    CONSTRAINT FK_PRICE_DAY  FOREIGN KEY (DAY_KY)
        REFERENCES DIM_DAY (DAY_KY)
);

