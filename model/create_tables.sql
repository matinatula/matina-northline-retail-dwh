-- ---------------------------------------------------------------------
-- PRODUCT HIERARCHY
-- ---------------------------------------------------------------------
CREATE TABLE DIM_BRAND (
    BRAND_KY        INT           NOT NULL,
    BRAND_ID        VARCHAR(50)   NOT NULL,
    BRAND_NAME      VARCHAR(200),
    CURR_FLG        BOOLEAN       NOT NULL DEFAULT TRUE,
    EFF_FROM_DT     DATE          NOT NULL,
    EFF_TO_DT       DATE          NOT NULL DEFAULT DATE '9999-12-31',
    REC_INS_TS      TIMESTAMP     NOT NULL,
    REC_UPDT_TS     TIMESTAMP     NOT NULL,
    SRC_SYS_CD      VARCHAR(30)   NOT NULL,
    BATCH_ID        VARCHAR(50)   NOT NULL,
    CONSTRAINT PK_DIM_BRAND PRIMARY KEY (BRAND_KY),
    CONSTRAINT UQ_DIM_BRAND_ID UNIQUE (BRAND_ID)
);

CREATE TABLE DIM_CATEGORY (
