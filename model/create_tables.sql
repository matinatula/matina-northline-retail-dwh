-- SCD2: one row per version of an item
CREATE TABLE DIM_ITEM (
    ITEM_KY         INT           NOT NULL,
    ITEM_ID         VARCHAR(50)   NOT NULL,
    ITEM_NAME       VARCHAR(200),
    SUBCATEGORY_KY  INT           NOT NULL,
    BRAND_KY        INT,
