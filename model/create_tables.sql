    CONSTRAINT PK_DIM_CATEGORY PRIMARY KEY (CATEGORY_KY),
    CONSTRAINT UQ_DIM_CATEGORY_ID UNIQUE (CATEGORY_ID)
);

CREATE TABLE DIM_SUBCATEGORY (
    SUBCATEGORY_KY    INT           NOT NULL,
    SUBCATEGORY_ID    VARCHAR(50)   NOT NULL,
    SUBCATEGORY_NAME  VARCHAR(200),
    CATEGORY_KY       INT           NOT NULL,
