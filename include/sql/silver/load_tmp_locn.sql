-- Silver: stores (locations), with rejects for missing keys.
-- Run by Airflow once per day. Airflow fills in the day (for example 2026-09-16) before running.

-- 1. Clear this day's earlier output so a re-run starts clean.
DELETE FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.TMP_LOCN WHERE BATCH_DT = '{{ ds }}'::DATE;
DELETE FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.C_REJ_TABLE WHERE BATCH_DT = '{{ ds }}'::DATE AND SRC_TABLE = 'STG_STORE_MASTER';

-- 2. Quarantine: a store with no id, district or region cannot be placed in the hierarchy.
INSERT INTO SNOWFLAKE_LEARNING_DB.MATINA_ETL.C_REJ_TABLE (BATCH_DT, SRC_TABLE, GATE, REASON_CODE, SRC_FILE_NM, ROW_PAYLOAD)
WITH clean AS (
    SELECT NULLIF(NULLIF(TRIM(STORE), ''), 'NULL') AS LOCN_ID,
           NULLIF(NULLIF(TRIM(STORE_NAME), ''), 'NULL') AS LOCN_NAME,
           NULLIF(NULLIF(TRIM(STORE_TYPE), ''), 'NULL') AS STORE_TYPE,
           NULLIF(NULLIF(TRIM(DISTRICT), ''), 'NULL') AS DISTRICT_ID,
           NULLIF(NULLIF(TRIM(DISTRICT_NAME), ''), 'NULL') AS DISTRICT_NAME,
           NULLIF(NULLIF(TRIM(REGION), ''), 'NULL') AS REGION_ID,
           NULLIF(NULLIF(TRIM(REGION_NAME), ''), 'NULL') AS REGION_NAME,
           TRY_TO_DATE(NULLIF(NULLIF(TRIM(STORE_OPEN_DATE), ''), 'NULL'))  AS OPEN_DT,
           TRY_TO_DATE(NULLIF(NULLIF(TRIM(STORE_CLOSE_DATE), ''), 'NULL')) AS CLOSE_DT,
           SRC_FILE_NM
    FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.STG_STORE_MASTER
    WHERE BATCH_DT = '{{ ds }}'::DATE
)
SELECT '{{ ds }}'::DATE, 'STG_STORE_MASTER', 'G4',
       CASE WHEN LOCN_ID IS NULL THEN 'NULL_STORE_ID' ELSE 'NULL_HIERARCHY' END,
       SRC_FILE_NM, OBJECT_CONSTRUCT(*)
FROM clean
WHERE NOT (LOCN_ID IS NOT NULL AND DISTRICT_ID IS NOT NULL AND REGION_ID IS NOT NULL);

-- 3. Good rows go to Silver, with the open and close dates turned into real dates.
--    The district id here is what the SCD2 step in Gold compares from day to day.
INSERT INTO SNOWFLAKE_LEARNING_DB.MATINA_ETL.TMP_LOCN (BATCH_DT, LOCN_ID, LOCN_NAME, DISTRICT_ID, STORE_TYPE, OPEN_DT, CLOSE_DT)
WITH clean AS (
    SELECT NULLIF(NULLIF(TRIM(STORE), ''), 'NULL') AS LOCN_ID,
           NULLIF(NULLIF(TRIM(STORE_NAME), ''), 'NULL') AS LOCN_NAME,
           NULLIF(NULLIF(TRIM(STORE_TYPE), ''), 'NULL') AS STORE_TYPE,
           NULLIF(NULLIF(TRIM(DISTRICT), ''), 'NULL') AS DISTRICT_ID,
           NULLIF(NULLIF(TRIM(DISTRICT_NAME), ''), 'NULL') AS DISTRICT_NAME,
           NULLIF(NULLIF(TRIM(REGION), ''), 'NULL') AS REGION_ID,
           NULLIF(NULLIF(TRIM(REGION_NAME), ''), 'NULL') AS REGION_NAME,
           TRY_TO_DATE(NULLIF(NULLIF(TRIM(STORE_OPEN_DATE), ''), 'NULL'))  AS OPEN_DT,
           TRY_TO_DATE(NULLIF(NULLIF(TRIM(STORE_CLOSE_DATE), ''), 'NULL')) AS CLOSE_DT,
           SRC_FILE_NM
    FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.STG_STORE_MASTER
    WHERE BATCH_DT = '{{ ds }}'::DATE
)
SELECT '{{ ds }}'::DATE, LOCN_ID, LOCN_NAME, DISTRICT_ID, STORE_TYPE, OPEN_DT, CLOSE_DT
FROM clean
WHERE LOCN_ID IS NOT NULL AND DISTRICT_ID IS NOT NULL AND REGION_ID IS NOT NULL
QUALIFY ROW_NUMBER() OVER (PARTITION BY LOCN_ID ORDER BY LOCN_NAME) = 1;
