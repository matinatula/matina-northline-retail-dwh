-- setup_etl.sql  |  Assignment 2.3  |  one-time setup of the ETL schema in Snowflake
-- Layers (one schema, prefixes show the layer):
--   STG_*  Bronze  raw text, as landed          TMP_*  Silver  typed and cleaned
--   DIM_*, FCT_*, AGG_*  Gold  the 2.1 model     C_REJ_TABLE  rejected rows
-- WARNING: re-running this script drops and recreates every table (empties the warehouse).
