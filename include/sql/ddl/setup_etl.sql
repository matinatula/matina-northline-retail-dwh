-- How COPY reads the files. Text stays text: the string 'NULL' is NOT turned into a real NULL here,
-- cleaning is Silver's job.
CREATE OR REPLACE FILE FORMAT ETL_CSV
    TYPE = CSV FIELD_DELIMITER = ',' SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"' NULL_IF = () EMPTY_FIELD_AS_NULL = TRUE ENCODING = 'UTF8';

