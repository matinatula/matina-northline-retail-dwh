-- ---------------------------------------------------------------------
-- SEED: calendar and customer. No source file feeds these, so they are seeded by hand
-- (the assignment allows this: "seed it manually and say so").
-- Keys are meaningful numbers: YEAR_KY = 2026, MONTH_KY = 202609, DAY_KY = 20260916.
-- ---------------------------------------------------------------------
INSERT INTO DIM_YEAR (YEAR_KY, YEAR_NUMBER, CURR_FLG, EFF_FROM_DT, EFF_TO_DT, REC_INS_TS, REC_UPDT_TS, SRC_SYS_CD, BATCH_ID)
SELECT y, y, TRUE, DATE '2025-01-01', DATE '9999-12-31', CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP(), 'SEED', 'SEED'
FROM (SELECT 2025 + SEQ4() AS y FROM TABLE(GENERATOR(ROWCOUNT => 3)));

