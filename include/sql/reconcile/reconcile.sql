-- Reconciliation for one business day. Each row is (check, expected, actual). The DAG fails if any row differs.
-- Gate G12: Bronze = Silver + rejects, and Silver = Gold + rejects, for counts and for money.
SELECT '1 sales rows: Bronze = Silver + rejects' AS CHECK_NAME,
       (SELECT COUNT(*) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.STG_POS_SALES WHERE BATCH_DT = '@DAY@')::NUMBER(38,2) AS EXPECTED,
       ((SELECT COUNT(*) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.TMP_SALES WHERE BATCH_DT = '@DAY@')
      + (SELECT COUNT(*) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.C_REJ_TABLE WHERE BATCH_DT = '@DAY@' AND SRC_TABLE = 'STG_POS_SALES'))::NUMBER(38,2) AS ACTUAL
UNION ALL
SELECT '2 sales net amount: source file = Silver + rejects',
       (SELECT COALESCE(SUM(TRY_TO_NUMBER(NET_AMT, 18, 2)), 0) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.STG_POS_SALES WHERE BATCH_DT = '@DAY@')::NUMBER(38,2),
       ((SELECT COALESCE(SUM(NET_AMT), 0) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.TMP_SALES WHERE BATCH_DT = '@DAY@')
      + (SELECT COALESCE(SUM(ROW_PAYLOAD:NET_AMT::NUMBER(18,2)), 0) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.C_REJ_TABLE WHERE BATCH_DT = '@DAY@' AND SRC_TABLE = 'STG_POS_SALES'))::NUMBER(38,2)
UNION ALL
SELECT '3 sales rows: Silver = Gold + rejects',
       (SELECT COUNT(*) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.TMP_SALES WHERE BATCH_DT = '@DAY@')::NUMBER(38,2),
       ((SELECT COUNT(*) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.FCT_SALES WHERE BATCH_ID = '@DAY@')
      + (SELECT COUNT(*) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.C_REJ_TABLE WHERE BATCH_DT = '@DAY@' AND SRC_TABLE = 'TMP_SALES'))::NUMBER(38,2)
UNION ALL
SELECT '4 sales net amount: Silver = Gold + rejects (extended - discount)',
       (SELECT COALESCE(SUM(SLS_AMT - COALESCE(DSC_AMT, 0)), 0) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.TMP_SALES WHERE BATCH_DT = '@DAY@')::NUMBER(38,2),
       ((SELECT COALESCE(SUM(SLS_AMT - COALESCE(DSC_AMT, 0)), 0) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.FCT_SALES WHERE BATCH_ID = '@DAY@')
      + (SELECT COALESCE(SUM(ROW_PAYLOAD:SLS_AMT::NUMBER(18,2) - COALESCE(ROW_PAYLOAD:DSC_AMT::NUMBER(18,2), 0)), 0) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.C_REJ_TABLE WHERE BATCH_DT = '@DAY@' AND SRC_TABLE = 'TMP_SALES'))::NUMBER(38,2)
UNION ALL
SELECT '5 inventory rows: Bronze = Silver + rejects',
       (SELECT COUNT(*) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.STG_INVENTORY_SNAPSHOT WHERE BATCH_DT = '@DAY@')::NUMBER(38,2),
       ((SELECT COUNT(*) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.TMP_INVENTORY WHERE BATCH_DT = '@DAY@')
      + (SELECT COUNT(*) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.C_REJ_TABLE WHERE BATCH_DT = '@DAY@' AND SRC_TABLE = 'STG_INVENTORY_SNAPSHOT'))::NUMBER(38,2)
UNION ALL
SELECT '6 inventory rows: Silver = Gold positions open that day + rejects',
       (SELECT COUNT(*) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.TMP_INVENTORY WHERE BATCH_DT = '@DAY@')::NUMBER(38,2),
       ((SELECT COUNT(*) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.FCT_INVENTORY WHERE '@DAY@'::DATE BETWEEN EFF_FROM_DT AND EFF_TO_DT)
      + (SELECT COUNT(*) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.C_REJ_TABLE WHERE BATCH_DT = '@DAY@' AND SRC_TABLE = 'TMP_INVENTORY'))::NUMBER(38,2)
UNION ALL
SELECT '7 inventory value: Silver = Gold positions open that day + rejects',
       (SELECT COALESCE(SUM(STK_VAL), 0) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.TMP_INVENTORY WHERE BATCH_DT = '@DAY@')::NUMBER(38,2),
       ((SELECT COALESCE(SUM(STK_VAL), 0) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.FCT_INVENTORY WHERE '@DAY@'::DATE BETWEEN EFF_FROM_DT AND EFF_TO_DT)
      + (SELECT COALESCE(SUM(ROW_PAYLOAD:STK_VAL::NUMBER(18,2)), 0) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.C_REJ_TABLE WHERE BATCH_DT = '@DAY@' AND SRC_TABLE = 'TMP_INVENTORY'))::NUMBER(38,2)
UNION ALL
SELECT '8 aggregate net amount: Gold facts of the month = aggregate of the month',
       (SELECT COALESCE(SUM(f.SLS_AMT - COALESCE(f.DSC_AMT, 0)), 0)
          FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.FCT_SALES f
          JOIN SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_DAY d ON d.DAY_KY = f.DAY_KY
         WHERE d.MONTH_KY = (SELECT MONTH_KY FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_DAY WHERE FULL_DT = '@DAY@'::DATE))::NUMBER(38,2),
       (SELECT COALESCE(SUM(SLS_AMT - COALESCE(DSC_AMT, 0)), 0)
          FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.AGG_SLS_DEPT_DISTRICT_MONTH
         WHERE MONTH_KY = (SELECT MONTH_KY FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_DAY WHERE FULL_DT = '@DAY@'::DATE))::NUMBER(38,2)
UNION ALL
SELECT '9 aggregate quantity: Gold facts of the month = aggregate of the month',
       (SELECT COALESCE(SUM(f.SLS_QTY), 0)
          FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.FCT_SALES f
          JOIN SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_DAY d ON d.DAY_KY = f.DAY_KY
         WHERE d.MONTH_KY = (SELECT MONTH_KY FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_DAY WHERE FULL_DT = '@DAY@'::DATE))::NUMBER(38,2),
       (SELECT COALESCE(SUM(SLS_QTY), 0)
          FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.AGG_SLS_DEPT_DISTRICT_MONTH
         WHERE MONTH_KY = (SELECT MONTH_KY FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_DAY WHERE FULL_DT = '@DAY@'::DATE))::NUMBER(38,2)
UNION ALL
SELECT '8 aggregate net amount: AGG for the month = FCT_SALES for the month',
       (SELECT COALESCE(SUM(f.SLS_AMT - COALESCE(f.DSC_AMT, 0)), 0)
          FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.FCT_SALES f
          JOIN SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_DAY d ON d.DAY_KY = f.DAY_KY
         WHERE d.MONTH_KY = (SELECT MONTH_KY FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_DAY WHERE FULL_DT = '@DAY@'::DATE))::NUMBER(38,2),
       (SELECT COALESCE(SUM(SLS_AMT - COALESCE(DSC_AMT, 0)), 0)
          FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.AGG_SLS_DEPT_DISTRICT_MONTH
         WHERE MONTH_KY = (SELECT MONTH_KY FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_DAY WHERE FULL_DT = '@DAY@'::DATE))::NUMBER(38,2)
ORDER BY 1;