-- Gold: FCT_PRICE (positional fact). One row = the price of an item at a store, valid from EFF_FROM_DT to
-- EFF_TO_DT (9999-12-31 = still the current price). Rows are CLOSED, never deleted.
-- A price stays open until a DIFFERENT price is seen: days with no sale of that item keep the old price.
-- A price row is also closed when its item or store version has ended (for example store 1112 moving district).
-- Rows that cannot get both keys go to C_REJ_TABLE (gate G11).
--
-- Guard (same idea as FCT_INVENTORY): the positional steps only run when this day is the latest one loaded,
-- so re-running an older day changes nothing, and re-running the latest day is undone and redone.

-- 1. Quarantine (G11).
DELETE FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.C_REJ_TABLE WHERE BATCH_DT = '{{ ds }}'::DATE AND SRC_TABLE = 'TMP_PRICE';
INSERT INTO SNOWFLAKE_LEARNING_DB.MATINA_ETL.C_REJ_TABLE (BATCH_DT, SRC_TABLE, GATE, REASON_CODE, SRC_FILE_NM, ROW_PAYLOAD)
WITH cls AS (
  SELECT p.*, i.ITEM_KY, l.LOCN_KY,
         CASE WHEN i.ITEM_KY IS NULL OR l.LOCN_KY IS NULL THEN 'NO_DIM_KEY' END AS REASON
  FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.TMP_PRICE p
  LEFT JOIN SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_ITEM i ON i.ITEM_ID = p.ITEM_ID AND p.BUSINESS_DT BETWEEN i.EFF_FROM_DT AND i.EFF_TO_DT
  LEFT JOIN SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_LOCN l ON l.LOCN_ID = p.LOCN_ID AND p.BUSINESS_DT BETWEEN l.EFF_FROM_DT AND l.EFF_TO_DT
  WHERE p.BATCH_DT = '{{ ds }}'::DATE
)
SELECT '{{ ds }}'::DATE, 'TMP_PRICE', 'G11', REASON, SRC_FILE_NM, OBJECT_CONSTRUCT(*)
FROM cls
WHERE REASON IS NOT NULL;

-- 2. Undo this day's earlier run: delete the rows it opened, reopen the rows it closed (they ended at day - 1).
DELETE FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.FCT_PRICE WHERE EFF_FROM_DT = '{{ ds }}'::DATE AND '{{ ds }}'::DATE >= (SELECT COALESCE(MAX(EFF_FROM_DT), '1900-01-01'::DATE) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.FCT_PRICE);
UPDATE SNOWFLAKE_LEARNING_DB.MATINA_ETL.FCT_PRICE SET EFF_TO_DT = '9999-12-31'::DATE, REC_UPDT_TS = SYSDATE()
WHERE EFF_TO_DT = DATEADD(day, -1, '{{ ds }}'::DATE) AND '{{ ds }}'::DATE >= (SELECT COALESCE(MAX(EFF_FROM_DT), '1900-01-01'::DATE) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.FCT_PRICE);

-- 3. Close: an open price ends the day before a different price is seen for the same item and store.
UPDATE SNOWFLAKE_LEARNING_DB.MATINA_ETL.FCT_PRICE f
SET EFF_TO_DT = DATEADD(day, -1, '{{ ds }}'::DATE), REC_UPDT_TS = SYSDATE(), BATCH_ID = '{{ ds }}'
FROM (
  SELECT ITEM_KY, LOCN_KY, PRICE_AMT FROM (
    SELECT p.*, i.ITEM_KY, l.LOCN_KY,
         CASE WHEN i.ITEM_KY IS NULL OR l.LOCN_KY IS NULL THEN 'NO_DIM_KEY' END AS REASON
  FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.TMP_PRICE p
  LEFT JOIN SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_ITEM i ON i.ITEM_ID = p.ITEM_ID AND p.BUSINESS_DT BETWEEN i.EFF_FROM_DT AND i.EFF_TO_DT
  LEFT JOIN SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_LOCN l ON l.LOCN_ID = p.LOCN_ID AND p.BUSINESS_DT BETWEEN l.EFF_FROM_DT AND l.EFF_TO_DT
  WHERE p.BATCH_DT = '{{ ds }}'::DATE
  ) WHERE REASON IS NULL
) s
WHERE f.ITEM_KY = s.ITEM_KY AND f.LOCN_KY = s.LOCN_KY
  AND f.EFF_TO_DT = '9999-12-31'::DATE AND f.EFF_FROM_DT < '{{ ds }}'::DATE AND '{{ ds }}'::DATE >= (SELECT COALESCE(MAX(EFF_FROM_DT), '1900-01-01'::DATE) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.FCT_PRICE)
  AND f.PRICE_AMT <> s.PRICE_AMT;

-- 4. Close: an open price whose item or store version is no longer the current one ends the day before.
UPDATE SNOWFLAKE_LEARNING_DB.MATINA_ETL.FCT_PRICE
SET EFF_TO_DT = DATEADD(day, -1, '{{ ds }}'::DATE), REC_UPDT_TS = SYSDATE(), BATCH_ID = '{{ ds }}'
WHERE EFF_TO_DT = '9999-12-31'::DATE AND EFF_FROM_DT < '{{ ds }}'::DATE AND '{{ ds }}'::DATE >= (SELECT COALESCE(MAX(EFF_FROM_DT), '1900-01-01'::DATE) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.FCT_PRICE)
  AND (LOCN_KY NOT IN (SELECT LOCN_KY FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_LOCN WHERE CURR_FLG)
    OR ITEM_KY NOT IN (SELECT ITEM_KY FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_ITEM WHERE CURR_FLG));

-- 5. Open: every observed item and store with no open price starts today (new pairs, and the ones closed above).
INSERT INTO SNOWFLAKE_LEARNING_DB.MATINA_ETL.FCT_PRICE
  (PRICE_KY, ITEM_KY, LOCN_KY, DAY_KY, PRICE_AMT, EFF_FROM_DT, EFF_TO_DT, REC_INS_TS, REC_UPDT_TS, SRC_SYS_CD, BATCH_ID)
SELECT (SELECT COALESCE(MAX(PRICE_KY), 0) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.FCT_PRICE) + ROW_NUMBER() OVER (ORDER BY g.ITEM_KY, g.LOCN_KY),
       g.ITEM_KY, g.LOCN_KY, (SELECT DAY_KY FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_DAY WHERE FULL_DT = '{{ ds }}'::DATE),
       g.PRICE_AMT, '{{ ds }}'::DATE, '9999-12-31'::DATE, SYSDATE(), SYSDATE(), 'POS', '{{ ds }}'
FROM (
  SELECT ITEM_KY, LOCN_KY, PRICE_AMT FROM (
    SELECT p.*, i.ITEM_KY, l.LOCN_KY,
         CASE WHEN i.ITEM_KY IS NULL OR l.LOCN_KY IS NULL THEN 'NO_DIM_KEY' END AS REASON
  FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.TMP_PRICE p
  LEFT JOIN SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_ITEM i ON i.ITEM_ID = p.ITEM_ID AND p.BUSINESS_DT BETWEEN i.EFF_FROM_DT AND i.EFF_TO_DT
  LEFT JOIN SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_LOCN l ON l.LOCN_ID = p.LOCN_ID AND p.BUSINESS_DT BETWEEN l.EFF_FROM_DT AND l.EFF_TO_DT
  WHERE p.BATCH_DT = '{{ ds }}'::DATE
  ) WHERE REASON IS NULL
) g
WHERE '{{ ds }}'::DATE >= (SELECT COALESCE(MAX(EFF_FROM_DT), '1900-01-01'::DATE) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.FCT_PRICE)
  AND (g.ITEM_KY, g.LOCN_KY) NOT IN (
    SELECT ITEM_KY, LOCN_KY FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.FCT_PRICE WHERE EFF_TO_DT = '9999-12-31'::DATE
  );
