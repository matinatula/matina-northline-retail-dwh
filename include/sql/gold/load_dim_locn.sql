-- Gold: DIM_LOCN (store, SCD2 = history kept).
-- A version is valid from EFF_FROM_DT to EFF_TO_DT (9999-12-31 = still open); CURR_FLG marks the open one.
-- Forward-only: a day only ever changes the OPEN version. Re-running any day that is already loaded
-- changes nothing, so the facts that point at these keys stay valid.

-- 1. Close: the open version of a key whose tracked attributes changed (name, district) ends the day before.
UPDATE SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_LOCN d
SET EFF_TO_DT = DATEADD(day, -1, '{{ ds }}'::DATE), CURR_FLG = FALSE, REC_UPDT_TS = SYSDATE(), BATCH_ID = '{{ ds }}'
FROM (
  SELECT s.LOCN_ID AS ID, s.LOCN_NAME AS NAME, c.DISTRICT_KY AS DKY
  FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.TMP_LOCN s
  JOIN SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_DISTRICT c ON c.DISTRICT_ID = s.DISTRICT_ID AND c.CURR_FLG
  WHERE s.BATCH_DT = '{{ ds }}'::DATE
) s
WHERE d.LOCN_ID = s.ID AND d.CURR_FLG AND d.EFF_FROM_DT < '{{ ds }}'::DATE
  AND (d.LOCN_NAME IS DISTINCT FROM s.NAME OR d.DISTRICT_KY IS DISTINCT FROM s.DKY);

-- 2. Same-day correction: if this day's own version is re-run with different values, fix it in place.
UPDATE SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_LOCN d
SET LOCN_NAME = s.NAME, DISTRICT_KY = s.DKY, REC_UPDT_TS = SYSDATE(), BATCH_ID = '{{ ds }}'
FROM (
  SELECT s.LOCN_ID AS ID, s.LOCN_NAME AS NAME, c.DISTRICT_KY AS DKY
  FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.TMP_LOCN s
  JOIN SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_DISTRICT c ON c.DISTRICT_ID = s.DISTRICT_ID AND c.CURR_FLG
  WHERE s.BATCH_DT = '{{ ds }}'::DATE
) s
WHERE d.LOCN_ID = s.ID AND d.CURR_FLG AND d.EFF_FROM_DT = '{{ ds }}'::DATE
  AND (d.LOCN_NAME IS DISTINCT FROM s.NAME OR d.DISTRICT_KY IS DISTINCT FROM s.DKY);

-- 3. Open: a new version for every key with no open version (brand new keys, and the ones closed in step 1).
INSERT INTO SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_LOCN
  (LOCN_KY, LOCN_ID, LOCN_NAME, DISTRICT_KY, CURR_FLG, EFF_FROM_DT, EFF_TO_DT, REC_INS_TS, REC_UPDT_TS, SRC_SYS_CD, BATCH_ID)
SELECT (SELECT COALESCE(MAX(LOCN_KY), 0) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_LOCN) + ROW_NUMBER() OVER (ORDER BY s.ID),
       s.ID, s.NAME, s.DKY, TRUE, '{{ ds }}'::DATE, '9999-12-31'::DATE, SYSDATE(), SYSDATE(), 'RMS', '{{ ds }}'
FROM (
  SELECT s.LOCN_ID AS ID, s.LOCN_NAME AS NAME, c.DISTRICT_KY AS DKY
  FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.TMP_LOCN s
  JOIN SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_DISTRICT c ON c.DISTRICT_ID = s.DISTRICT_ID AND c.CURR_FLG
  WHERE s.BATCH_DT = '{{ ds }}'::DATE
) s
WHERE NOT EXISTS (SELECT 1 FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_LOCN d WHERE d.LOCN_ID = s.ID AND d.CURR_FLG);