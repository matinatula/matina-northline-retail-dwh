-- Gold: DIM_DISTRICT (district, SCD1 = overwrite, no history). Built from TMP_DISTRICT.
-- Run by Airflow once per day. Safe to re-run: unchanged rows are untouched, new rows are only added once.

-- 1. Existing rows whose name or parent changed are overwritten in place.
UPDATE SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_DISTRICT d
SET DISTRICT_NAME = s.NAME,
    REGION_KY = s.PKY,
    REC_UPDT_TS = SYSDATE(),
    BATCH_ID = '{{ ds }}'
FROM (
  SELECT s.DISTRICT_ID AS ID, s.DISTRICT_NAME AS NAME, p.REGION_KY AS PKY
  FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.TMP_DISTRICT s
  JOIN SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_REGION p ON p.REGION_ID = s.REGION_ID AND p.CURR_FLG
  WHERE s.BATCH_DT = '{{ ds }}'::DATE
) s
WHERE d.DISTRICT_ID = s.ID
  AND (d.DISTRICT_NAME IS DISTINCT FROM s.NAME
     OR d.REGION_KY IS DISTINCT FROM s.PKY);

-- 2. Ids that are not in the dimension yet get a new surrogate key (current max + 1, 2, 3 ...).
INSERT INTO SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_DISTRICT
  (DISTRICT_KY, DISTRICT_ID, DISTRICT_NAME, REGION_KY, CURR_FLG, EFF_FROM_DT, EFF_TO_DT, REC_INS_TS, REC_UPDT_TS, SRC_SYS_CD, BATCH_ID)
SELECT (SELECT COALESCE(MAX(DISTRICT_KY), 0) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_DISTRICT) + ROW_NUMBER() OVER (ORDER BY s.ID),
       s.ID, s.NAME, s.PKY, TRUE, '{{ ds }}'::DATE, '9999-12-31'::DATE, SYSDATE(), SYSDATE(), 'RMS', '{{ ds }}'
FROM (
  SELECT s.DISTRICT_ID AS ID, s.DISTRICT_NAME AS NAME, p.REGION_KY AS PKY
  FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.TMP_DISTRICT s
  JOIN SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_REGION p ON p.REGION_ID = s.REGION_ID AND p.CURR_FLG
  WHERE s.BATCH_DT = '{{ ds }}'::DATE
) s
WHERE NOT EXISTS (SELECT 1 FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_DISTRICT d WHERE d.DISTRICT_ID = s.ID);
