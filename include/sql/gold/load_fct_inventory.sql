-- Gold: FCT_INVENTORY (positional fact). One row = one stock position for an item at a location,
-- valid from EFF_FROM_DT to EFF_TO_DT (9999-12-31 = still open). Rows are CLOSED, never deleted:
-- a row ends the day before the stock changes (or the row disappears), and a new row starts that day.
-- Rows that cannot get both keys, or have no value, go to C_REJ_TABLE (gate G11).
--
-- Guard: every positional step runs only if this day is the latest one loaded. A re-run of an older day
-- therefore changes nothing (its history is already in the table). A re-run of the latest day is
-- undone and redone in steps 2 and 3.

-- 1. Quarantine (G11). Depends only on the dimensions valid on this day, so it is safe for any day.
DELETE FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.C_REJ_TABLE WHERE BATCH_DT = '{{ ds }}'::DATE AND SRC_TABLE = 'TMP_INVENTORY';
INSERT INTO SNOWFLAKE_LEARNING_DB.MATINA_ETL.C_REJ_TABLE (BATCH_DT, SRC_TABLE, GATE, REASON_CODE, SRC_FILE_NM, ROW_PAYLOAD)
WITH cls AS (
  SELECT s.*, i.ITEM_KY, l.LOCN_KY,
         CASE WHEN i.ITEM_KY IS NULL OR l.LOCN_KY IS NULL THEN 'NO_DIM_KEY'
              WHEN s.STK_VAL IS NULL THEN 'NULL_STK_VAL' END AS REASON
  FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.TMP_INVENTORY s
  LEFT JOIN SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_ITEM i ON i.ITEM_ID = s.ITEM_ID AND '{{ ds }}'::DATE BETWEEN i.EFF_FROM_DT AND i.EFF_TO_DT
  LEFT JOIN SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_LOCN l ON l.LOCN_ID = s.LOCN_ID AND '{{ ds }}'::DATE BETWEEN l.EFF_FROM_DT AND l.EFF_TO_DT
  WHERE s.BATCH_DT = '{{ ds }}'::DATE
)
SELECT '{{ ds }}'::DATE, 'TMP_INVENTORY', 'G11', REASON, SRC_FILE_NM, OBJECT_CONSTRUCT(*)
FROM cls
WHERE REASON IS NOT NULL;

-- 2. Undo this day's earlier run: delete the rows it opened, reopen the rows it closed (they ended at day - 1).
DELETE FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.FCT_INVENTORY WHERE EFF_FROM_DT = '{{ ds }}'::DATE AND '{{ ds }}'::DATE >= (SELECT COALESCE(MAX(EFF_FROM_DT), '1900-01-01'::DATE) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.FCT_INVENTORY);
UPDATE SNOWFLAKE_LEARNING_DB.MATINA_ETL.FCT_INVENTORY SET EFF_TO_DT = '9999-12-31'::DATE, REC_UPDT_TS = SYSDATE()
WHERE EFF_TO_DT = DATEADD(day, -1, '{{ ds }}'::DATE) AND '{{ ds }}'::DATE >= (SELECT COALESCE(MAX(EFF_FROM_DT), '1900-01-01'::DATE) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.FCT_INVENTORY);

-- 3. Close: open rows whose stock changed, or that are no longer in today's snapshot, end the day before.
UPDATE SNOWFLAKE_LEARNING_DB.MATINA_ETL.FCT_INVENTORY
SET EFF_TO_DT = DATEADD(day, -1, '{{ ds }}'::DATE), REC_UPDT_TS = SYSDATE(), BATCH_ID = '{{ ds }}'
WHERE EFF_TO_DT = '9999-12-31'::DATE AND EFF_FROM_DT < '{{ ds }}'::DATE AND '{{ ds }}'::DATE >= (SELECT COALESCE(MAX(EFF_FROM_DT), '1900-01-01'::DATE) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.FCT_INVENTORY)
  AND (ITEM_KY, LOCN_KY, STK_QTY, STK_VAL) NOT IN (
    SELECT ITEM_KY, LOCN_KY, STK_QTY, STK_VAL FROM (
    SELECT s.*, i.ITEM_KY, l.LOCN_KY,
         CASE WHEN i.ITEM_KY IS NULL OR l.LOCN_KY IS NULL THEN 'NO_DIM_KEY'
              WHEN s.STK_VAL IS NULL THEN 'NULL_STK_VAL' END AS REASON
  FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.TMP_INVENTORY s
  LEFT JOIN SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_ITEM i ON i.ITEM_ID = s.ITEM_ID AND '{{ ds }}'::DATE BETWEEN i.EFF_FROM_DT AND i.EFF_TO_DT
  LEFT JOIN SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_LOCN l ON l.LOCN_ID = s.LOCN_ID AND '{{ ds }}'::DATE BETWEEN l.EFF_FROM_DT AND l.EFF_TO_DT
  WHERE s.BATCH_DT = '{{ ds }}'::DATE
  ) WHERE REASON IS NULL
  );

-- 4. Open: every position with no open row starts today (new positions, and the ones closed in step 3).
INSERT INTO SNOWFLAKE_LEARNING_DB.MATINA_ETL.FCT_INVENTORY
  (INVENTORY_KY, ITEM_KY, LOCN_KY, DAY_KY, STK_QTY, STK_VAL, EFF_FROM_DT, EFF_TO_DT,
   REC_INS_TS, REC_UPDT_TS, SRC_SYS_CD, BATCH_ID)
SELECT (SELECT COALESCE(MAX(INVENTORY_KY), 0) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.FCT_INVENTORY) + ROW_NUMBER() OVER (ORDER BY g.ITEM_KY, g.LOCN_KY),
       g.ITEM_KY, g.LOCN_KY, (SELECT DAY_KY FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_DAY WHERE FULL_DT = '{{ ds }}'::DATE),
       g.STK_QTY, g.STK_VAL, '{{ ds }}'::DATE, '9999-12-31'::DATE, SYSDATE(), SYSDATE(), 'RMS', '{{ ds }}'
FROM (
  SELECT ITEM_KY, LOCN_KY, STK_QTY, STK_VAL FROM (
    SELECT s.*, i.ITEM_KY, l.LOCN_KY,
         CASE WHEN i.ITEM_KY IS NULL OR l.LOCN_KY IS NULL THEN 'NO_DIM_KEY'
              WHEN s.STK_VAL IS NULL THEN 'NULL_STK_VAL' END AS REASON
  FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.TMP_INVENTORY s
  LEFT JOIN SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_ITEM i ON i.ITEM_ID = s.ITEM_ID AND '{{ ds }}'::DATE BETWEEN i.EFF_FROM_DT AND i.EFF_TO_DT
  LEFT JOIN SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_LOCN l ON l.LOCN_ID = s.LOCN_ID AND '{{ ds }}'::DATE BETWEEN l.EFF_FROM_DT AND l.EFF_TO_DT
  WHERE s.BATCH_DT = '{{ ds }}'::DATE
  ) WHERE REASON IS NULL
) g
WHERE '{{ ds }}'::DATE >= (SELECT COALESCE(MAX(EFF_FROM_DT), '1900-01-01'::DATE) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.FCT_INVENTORY)
  AND (g.ITEM_KY, g.LOCN_KY) NOT IN (
    SELECT ITEM_KY, LOCN_KY FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.FCT_INVENTORY WHERE EFF_TO_DT = '9999-12-31'::DATE
  );
