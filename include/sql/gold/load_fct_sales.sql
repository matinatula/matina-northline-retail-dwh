-- Gold: FCT_SALES (transaction fact). Grain: item, location, day, transaction line.
-- Built from TMP_SALES. Each sale takes the item and store VERSION that was valid on its business date
-- (this is what makes SCD2 useful: a sale at store 1112 before 2026-09-20 keeps district 104).
-- Rows that cannot get all three keys, or have no amount, go to C_REJ_TABLE (gate G11). Nothing is dropped silently.

-- 1. Clear this day's earlier output so a re-run starts clean (the fact rows are tagged with the day in BATCH_ID).
DELETE FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.FCT_SALES WHERE BATCH_ID = '{{ ds }}';
DELETE FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.C_REJ_TABLE WHERE BATCH_DT = '{{ ds }}'::DATE AND SRC_TABLE = 'TMP_SALES';

-- 2. Quarantine (G11).
INSERT INTO SNOWFLAKE_LEARNING_DB.MATINA_ETL.C_REJ_TABLE (BATCH_DT, SRC_TABLE, GATE, REASON_CODE, SRC_FILE_NM, ROW_PAYLOAD)
WITH cls AS (
  SELECT s.*, i.ITEM_KY, l.LOCN_KY, d.DAY_KY,
         CASE WHEN i.ITEM_KY IS NULL OR l.LOCN_KY IS NULL OR d.DAY_KY IS NULL THEN 'NO_DIM_KEY'
              WHEN s.SLS_AMT IS NULL THEN 'NULL_AMOUNT' END AS REASON
  FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.TMP_SALES s
  LEFT JOIN SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_ITEM i ON i.ITEM_ID = s.ITEM_ID AND s.BUSINESS_DT BETWEEN i.EFF_FROM_DT AND i.EFF_TO_DT
  LEFT JOIN SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_LOCN l ON l.LOCN_ID = s.LOCN_ID AND s.BUSINESS_DT BETWEEN l.EFF_FROM_DT AND l.EFF_TO_DT
  LEFT JOIN SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_DAY  d ON d.FULL_DT = s.BUSINESS_DT
  WHERE s.BATCH_DT = '{{ ds }}'::DATE
)
SELECT '{{ ds }}'::DATE, 'TMP_SALES', 'G11', REASON, SRC_FILE_NM, OBJECT_CONSTRUCT(*)
FROM cls
WHERE REASON IS NOT NULL;

-- 3. Good rows into the fact. SALES_KY = current max + 1, 2, 3 ... ; customer is the seeded Unknown row.
INSERT INTO SNOWFLAKE_LEARNING_DB.MATINA_ETL.FCT_SALES
  (SALES_KY, TRANSACTION_ID, LINE_NUMBER, ITEM_KY, LOCN_KY, DAY_KY, CUSTOMER_KY, SLS_QTY, SLS_AMT, DSC_AMT,
   REC_INS_TS, REC_UPDT_TS, SRC_SYS_CD, BATCH_ID)
WITH cls AS (
  SELECT s.*, i.ITEM_KY, l.LOCN_KY, d.DAY_KY,
         CASE WHEN i.ITEM_KY IS NULL OR l.LOCN_KY IS NULL OR d.DAY_KY IS NULL THEN 'NO_DIM_KEY'
              WHEN s.SLS_AMT IS NULL THEN 'NULL_AMOUNT' END AS REASON
  FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.TMP_SALES s
  LEFT JOIN SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_ITEM i ON i.ITEM_ID = s.ITEM_ID AND s.BUSINESS_DT BETWEEN i.EFF_FROM_DT AND i.EFF_TO_DT
  LEFT JOIN SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_LOCN l ON l.LOCN_ID = s.LOCN_ID AND s.BUSINESS_DT BETWEEN l.EFF_FROM_DT AND l.EFF_TO_DT
  LEFT JOIN SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_DAY  d ON d.FULL_DT = s.BUSINESS_DT
  WHERE s.BATCH_DT = '{{ ds }}'::DATE
)
SELECT (SELECT COALESCE(MAX(SALES_KY), 0) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.FCT_SALES) + ROW_NUMBER() OVER (ORDER BY TRANSACTION_ID, LINE_NUMBER),
       TRANSACTION_ID, LINE_NUMBER, ITEM_KY, LOCN_KY, DAY_KY,
       (SELECT MIN(CUSTOMER_KY) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_CUSTOMER),
       SLS_QTY, SLS_AMT, DSC_AMT, SYSDATE(), SYSDATE(), 'POS', '{{ ds }}'
FROM cls
WHERE REASON IS NULL;
