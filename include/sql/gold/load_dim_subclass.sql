-- Gold: DIM_SUBCLASS (subclass, SCD1 = overwrite, no history). Built from TMP_SUBCLASS.
-- Run by Airflow once per day. Safe to re-run: unchanged rows are untouched, new rows are only added once.

-- 1. Existing rows whose name or parent changed are overwritten in place.
UPDATE SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_SUBCLASS d
SET SUBCLASS_NAME = s.NAME,
    DEPT_KY = s.PKY,
    REC_UPDT_TS = SYSDATE(),
    BATCH_ID = '{{ ds }}'
FROM (
  SELECT s.SUBCLASS_ID AS ID, s.SUBCLASS_NAME AS NAME, p.DEPT_KY AS PKY
  FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.TMP_SUBCLASS s
  JOIN SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_DEPT p ON p.DEPT_ID = s.DEPT_ID AND p.CURR_FLG
  WHERE s.BATCH_DT = '{{ ds }}'::DATE
) s
WHERE d.SUBCLASS_ID = s.ID
  AND (d.SUBCLASS_NAME IS DISTINCT FROM s.NAME
     OR d.DEPT_KY IS DISTINCT FROM s.PKY);

-- 2. Ids that are not in the dimension yet get a new surrogate key (current max + 1, 2, 3 ...).
INSERT INTO SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_SUBCLASS
  (SUBCLASS_KY, SUBCLASS_ID, SUBCLASS_NAME, DEPT_KY, CURR_FLG, EFF_FROM_DT, EFF_TO_DT, REC_INS_TS, REC_UPDT_TS, SRC_SYS_CD, BATCH_ID)
SELECT (SELECT COALESCE(MAX(SUBCLASS_KY), 0) FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_SUBCLASS) + ROW_NUMBER() OVER (ORDER BY s.ID),
       s.ID, s.NAME, s.PKY, TRUE, '{{ ds }}'::DATE, '9999-12-31'::DATE, SYSDATE(), SYSDATE(), 'RMS', '{{ ds }}'
FROM (
  SELECT s.SUBCLASS_ID AS ID, s.SUBCLASS_NAME AS NAME, p.DEPT_KY AS PKY
  FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.TMP_SUBCLASS s
  JOIN SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_DEPT p ON p.DEPT_ID = s.DEPT_ID AND p.CURR_FLG
  WHERE s.BATCH_DT = '{{ ds }}'::DATE
) s
WHERE NOT EXISTS (SELECT 1 FROM SNOWFLAKE_LEARNING_DB.MATINA_ETL.DIM_SUBCLASS d WHERE d.SUBCLASS_ID = s.ID);
